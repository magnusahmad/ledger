// Real fictional appointment → signing approval; secret link stays in private storage.
import "../../src/domain/inbound";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { eq } from "drizzle-orm";
import { PDFDocument } from "pdf-lib";
import { makeRuntimeCtx } from "../../src/lib/runtime";
import { createRequest, startTask, markStepState } from "../../src/domain/engine";
import { createPerson } from "../../src/domain/records";
import { portalUpload } from "../../src/domain/portal";
import { approveProposal, pendingProposals } from "../../src/domain/proposals";
import { document, signer } from "../../src/db/schema";
import { ScriptedLlm } from "../../src/integrations/llm/scripted";
import { FakeMail } from "../../src/integrations/mail/fake";
import { Crypto } from "../../src/lib/crypto";

if (!process.env.DATABASE_URL?.endsWith("_e2e") || process.env.MAIL_PROVIDER !== "fake" || process.env.LLM_MODE !== "e2e") throw new Error("OTP browser fixtures require isolated E2E database and fake providers");
const base = makeRuntimeCtx();
if (!(base.mail instanceof FakeMail)) throw new Error("OTP browser fixture cannot use a live mailbox");
const ctx = { ...base, llm: new ScriptedLlm().on("extract", { fields: [], documents: [], conflicts: [] }) };
const req = await createRequest(ctx, { clientId: "cli_c1" });
const person = await createPerson(ctx, { nameEn: "OTP Appointee 繁體 简体", email: "otp.appointee@fictional.example", idNumber: "K987654(3)", residentialAddress: "Fictional home", correspondenceAddress: "Fictional office" });
const task = await startTask(ctx, { requestId: req.id, clientId: "cli_c1", playbookId: "hk.appointDirector", personId: person.id, extracted: { effDate: { value: "2026-09-29" } } });
await markStepState(ctx, task.id, "send", { sent: true });
const pdf = await PDFDocument.create(); pdf.addPage(); const bytes = Buffer.from(await pdf.save());
for (const key of ["idCopy", "addrProof"]) await portalUpload(ctx, req.uploadToken, { taskId: task.id, key, filename: `${key}.pdf`, mime: "application/pdf", content: bytes });
await portalUpload(ctx, req.uploadToken, { taskId: task.id, key: "selfie", filename: "selfie.png", mime: "image/png", content: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==", "base64") });
const card = (await pendingProposals(ctx, { kind: "send_signing", taskId: task.id }))[0];
if (!card) throw new Error("OTP fixture did not reach real signing approval");
const docs = [...new Set((card.payload.signers as { docIds: string[] }[]).flatMap(s => s.docIds))];
for (const [i, id] of docs.entries()) await ctx.db.update(document).set({ title: `Signing document ${i + 1} 董事任命确认文件.pdf` }).where(eq(document.id, id));
await approveProposal(ctx, card.id);
const invitation = base.mail.sent().find(m => m.to.includes(person.email!) && m.subject.startsWith("Documents to sign:"));
const token = invitation?.text.match(/\/sign\/([A-Za-z0-9]+)/)?.[1];
if (!token) throw new Error("OTP fixture has no accepted signing invitation");
const row = await ctx.db.query.signer.findFirst({ where: eq(signer.tokenHash, Crypto.sha256(token)) });
if (!row) throw new Error("OTP fixture signer was not persisted");
writeFileSync(path.join(process.env.STORAGE_DIR!, "otp-access-case.json"), JSON.stringify({ token, signerId: row.id, email: person.email, taskId: task.id }));
process.exit(0);
