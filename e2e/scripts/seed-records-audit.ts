import path from 'node:path';
import { makeRuntimeCtx, STORAGE_ROOT } from '../../src/lib/runtime';
import { createRequest, startTask, markStepState, advance } from '../../src/domain/engine';
import { approveProposal, pendingProposals } from '../../src/domain/proposals';
import { closePools } from '../../src/db/client';
import '../../src/domain/inbound';
import { readFileSync, writeFileSync } from 'node:fs';
const ctx = makeRuntimeCtx();
const req = await createRequest(ctx, { clientId: 'cli_c1' });
await startTask(ctx, { requestId: req.id, clientId: 'cli_c1', playbookId: 'hk.changeOffice' });
const signingReq = await createRequest(ctx, { clientId: 'cli_c1' });
const t = await startTask(ctx, { requestId: signingReq.id, clientId: 'cli_c1', playbookId: 'hk.changeOffice', extracted: { newAddr: { value: 'Audit new office' }, effDate: { value: ctx.clock.today() } } });
await markStepState(ctx, t.id, 'send', { sent: true });
await advance(ctx, t.id);
await approveProposal(ctx, (await pendingProposals(ctx, { taskId: t.id, kind: 'send_signing' }))[0].id);
const mails = JSON.parse(readFileSync(path.join(STORAGE_ROOT, 'fake/outbox.json'), 'utf8'));
const token = mails.at(-1).text.match(/\/sign\/([A-Za-z0-9]+)/)[1];
writeFileSync(path.join(STORAGE_ROOT, 'audit-links.json'), JSON.stringify({ portal: req.uploadToken, signing: token }));
await closePools();
